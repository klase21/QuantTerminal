export function listMockInformationItems(query: InformationRepositoryQuery = {}) {
  return mockInformationItems
    .filter((item) => !query.symbol || item.assetTags.includes(query.symbol) || item.symbol === query.symbol)
    .filter((item) => !query.provider || item.source.provider === query.provider)
    .filter((item) => !query.narrativeTag || item.narrativeTags.includes(query.narrativeTag))
    .slice(0, query.limit ?? mockInformationItems.length)
}

export function getMockInformationItem(id: string) {
  return mockInformationItems.find((item) => item.id === id) ?? null
}

