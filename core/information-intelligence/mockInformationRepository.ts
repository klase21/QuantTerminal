const NOW = "2026-06-08T00:00:00.000Z"

function source(provider: InformationSourceProvider): InformationSource {
  const classification = informationSourceClassifications.find((item) => item.provider === provider)
  return {
    id: `source-${provider}`,
    provider,
    category: classification?.category ?? "news",
    displayName: classification?.displayName ?? provider,
    verificationMode: classification?.verificationMode ?? "unverified",
    reputationScore: classification?.defaultReputationScore ?? 45,
  }
}

